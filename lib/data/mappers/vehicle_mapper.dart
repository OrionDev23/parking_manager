import '../../domain/entities/vehicle.dart' as domain;
import '../../serializables/vehicle/vehicle.dart' as legacy;

class VehicleMapper {
  static domain.Vehicle toDomain(
    legacy.Vehicle vehicle, {
    required String companyId,
    String? siteId,
  }) {
    final now = DateTime.now().toUtc();
    return domain.Vehicle(
      id: vehicle.id,
      companyId: companyId,
      siteId: siteId,
      registration: vehicle.matricule,
      foreignRegistration: vehicle.matriculeEtrang,
      wilaya: vehicle.wilaya,
      commune: vehicle.commune,
      daira: vehicle.daira,
      address: vehicle.adresse,
      registrationDate: vehicle.date,
      receiptAmount: vehicle.quittance,
      receiptNumber: vehicle.numero,
      ownerLastName: vehicle.nom,
      ownerFirstName: vehicle.prenom,
      ownerProfession: vehicle.profession,
      serialNumber: vehicle.numeroSerie,
      trim: vehicle.trim,
      modelYear: vehicle.modelYear,
      imageFileId: vehicle.imageFileId,
      imageUrl: vehicle.imageUrl,
      imageSource: vehicle.imageSource,
      color: vehicle.color,
      engineDisplacement: vehicle.engineDisplacement,
      engineCode: vehicle.engineCode,
      transmission: vehicle.transmission,
      gearbox: vehicle.gearbox,
      driveType: vehicle.driveType,
      doors: vehicle.doors,
      lengthMm: vehicle.lengthMm,
      widthMm: vehicle.widthMm,
      heightMm: vehicle.heightMm,
      acquisitionType: vehicle.acquisitionType,
      acquisitionDate: DateTime.tryParse(vehicle.acquisitionDate ?? ''),
      purchasePrice: vehicle.purchasePrice,
      supplier: vehicle.supplier,
      warrantyEndDate: DateTime.tryParse(vehicle.warrantyEndDate ?? ''),
      fleetNumber: vehicle.fleetNumber,
      currentMileage: vehicle.currentMileage,
      nextServiceMileage: vehicle.nextServiceMileage,
      customFields: vehicle.customFields ?? const {},
      type: vehicle.type,
      brand: vehicle.marque,
      genre: vehicle.genre,
      usefulLoad: vehicle.charegeUtile,
      totalWeight: vehicle.poidsTotal,
      seats: vehicle.placesAssises,
      power: vehicle.puissance,
      energy: vehicle.energie,
      body: vehicle.carrosserie,
      usageYear: vehicle.anneeUtil,
      previousRegistrations: vehicle.matriculePrec ?? const [],
      createdBy: vehicle.createdBy,
      country: vehicle.pays,
      state: vehicle.etat,
      currentState: vehicle.etatactuel,
      subsidiary: vehicle.filliale,
      department: vehicle.departement,
      direction: vehicle.direction,
      ownership: vehicle.appartenance,
      driverOwnership: vehicle.appartenanceconducteur,
      service: vehicle.service,
      driverRegistration: vehicle.matriculeConducteur,
      heavy: vehicle.lourd,
      decision: vehicle.decision,
      location: vehicle.emplacement,
      perimeter: vehicle.perimetre,
      createdAt: vehicle.createdAt ?? now,
      updatedAt: vehicle.updatedAt ?? now,
    );
  }

  static legacy.Vehicle toLegacy(domain.Vehicle vehicle) {
    return legacy.Vehicle(
      id: vehicle.id,
      matricule: vehicle.registration,
      matriculeEtrang: vehicle.foreignRegistration,
      wilaya: vehicle.wilaya,
      commune: vehicle.commune,
      daira: vehicle.daira,
      adresse: vehicle.address,
      date: vehicle.registrationDate,
      quittance: vehicle.receiptAmount,
      numero: vehicle.receiptNumber,
      nom: vehicle.ownerLastName,
      prenom: vehicle.ownerFirstName,
      profession: vehicle.ownerProfession,
      numeroSerie: vehicle.serialNumber,
      trim: vehicle.trim,
      modelYear: vehicle.modelYear,
      imageFileId: vehicle.imageFileId,
      imageUrl: vehicle.imageUrl,
      imageSource: vehicle.imageSource,
      color: vehicle.color,
      engineDisplacement: vehicle.engineDisplacement,
      engineCode: vehicle.engineCode,
      transmission: vehicle.transmission,
      gearbox: vehicle.gearbox,
      driveType: vehicle.driveType,
      doors: vehicle.doors,
      lengthMm: vehicle.lengthMm,
      widthMm: vehicle.widthMm,
      heightMm: vehicle.heightMm,
      acquisitionType: vehicle.acquisitionType,
      acquisitionDate: vehicle.acquisitionDate?.toIso8601String(),
      purchasePrice: vehicle.purchasePrice,
      supplier: vehicle.supplier,
      warrantyEndDate: vehicle.warrantyEndDate?.toIso8601String(),
      fleetNumber: vehicle.fleetNumber,
      currentMileage: vehicle.currentMileage,
      nextServiceMileage: vehicle.nextServiceMileage,
      customFields: vehicle.customFields,
      type: vehicle.type,
      marque: vehicle.brand,
      genre: vehicle.genre,
      charegeUtile: vehicle.usefulLoad,
      poidsTotal: vehicle.totalWeight,
      placesAssises: vehicle.seats,
      puissance: vehicle.power,
      energie: vehicle.energy,
      carrosserie: vehicle.body,
      anneeUtil: vehicle.usageYear,
      matriculePrec: vehicle.previousRegistrations,
      createdBy: vehicle.createdBy,
      pays: vehicle.country,
      etat: vehicle.state,
      etatactuel: vehicle.currentState,
      filliale: vehicle.subsidiary,
      departement: vehicle.department,
      direction: vehicle.direction,
      appartenance: vehicle.ownership,
      appartenanceconducteur: vehicle.driverOwnership,
      service: vehicle.service,
      matriculeConducteur: vehicle.driverRegistration,
      lourd: vehicle.heavy,
      decision: vehicle.decision,
      emplacement: vehicle.location,
      perimetre: vehicle.perimeter,
      createdAt: vehicle.createdAt,
      updatedAt: vehicle.updatedAt,
    );
  }
}
